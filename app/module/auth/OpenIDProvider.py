OPENID_TIMEOUT = 10 #Timeout in seconds for every request made to the openid server


class _RedisStateIntegration(FlaskIntegration):
    """
    authlib stores the state data (redirect_uri, nonce, and code_verifier with pkce) in the flask session by default.
    It is stored in redis instead, under sso_state:<name>:<state>, with a TTL of cs.SSO_STATE_TTL.
    The name is bound to the callback url, so a state can only be used on the callback of its kind and domain.
    The flask session given by authlib is ignored.
    If redis is unreachable, raise RequestException(ERROR_SSO_STATE_STORAGE_UNREACHABLE).
    The last state data read is kept in read_state_data: authlib does not give it back.
    """

    read_state_data: dict | None = None

    def _get_key(self, state: str) -> str:
        return f"{cs.SSO_STATE_KEY_PREFIX}{self.name}:{state}"

    def set_state_data(self, session: SessionMixin, state: str, data: dict) -> None:
        key = self._get_key(state)
        cache = sogo_cache()
        try:
            cache.set(key, data, self.expires_in)
        except (rexc.ConnectionError, rexc.TimeoutError) as e:
            logger_auth.error("Cannot save the openid state in redis: %s", repr(e))
            raise RequestException(error=err.ERROR_SSO_STATE_STORAGE_UNREACHABLE) from e
        finally:
            cache.close()

    def get_state_data(self, session: SessionMixin, state: str | None) -> dict | None:
        """
        Read and delete the state data (GETDEL): the state is single use, even with concurrent callbacks.
        None if the state is missing, unknown, expired (TTL) or already used -> authlib raises MismatchingStateError
        """
        if not state:
            return None
        key = self._get_key(state)
        cache = sogo_cache()
        try:
            data = cache.pop(key, dict)
        except (rexc.ConnectionError, rexc.TimeoutError) as e:
            logger_auth.error("Cannot read the openid state from redis: %s", repr(e))
            raise RequestException(error=err.ERROR_SSO_STATE_STORAGE_UNREACHABLE) from e
        finally:
            cache.close()
        self.read_state_data = data if isinstance(data, dict) else None
        return self.read_state_data

    def clear_state_data(self, session: SessionMixin, state: str | None) -> None:
        """Nothing to do, get_state_data already deleted the state"""


class OpenIDProvider(IdentityProvider):
    """
    OpenID Connect identity provider, authorization code flow, using the flask integration of authlib.

    The state (and the nonce, generated by authlib because of the 'openid' scope) is stored in redis
    (see _RedisStateIntegration), under a key bound to the callback url: the callback must be made
    for the same kind and domain, within cs.SSO_STATE_TTL, and only once.
    The UI url is stored with them (cs.SSO_STATE_UI_REDIRECT), authlib ignores the extra keys of the state data.

    Every exchange with the openid server is done by authlib: the flask client (FlaskOAuth2App) for the login flow
    and the userinfo endpoint, an authlib requests session (OAuth2Session) for the refresh and the introspection,
    that the flask client does not expose. Both use the same client settings (see _get_client_settings).
    TODO pkce: add code_challenge_method="S256" in client_kwargs, authlib does the rest.
    """

    kind = "openid"

    def __init__(self, auth_settings: AuthSettingsObj, callback_url: str):
        """
        Initialize the openid provider

        :param auth_settings: Authentication settings of the domain, SOGO_D_AUTH_TYPE must be 'openid'
        :type auth_settings: AuthSettingsObj
        :param callback_url: API url called by the openid server after the user logged in (redirect_uri)
        :type callback_url: str
        """
        super().__init__(auth_settings, callback_url)
        self._framework = _RedisStateIntegration(f"{self.kind}:{self.callback_url}")
        self._framework.expires_in = cs.SSO_STATE_TTL
        self._client = self._create_client()

    def _get_client_settings(self) -> dict:
        """
        Settings of the openid client, shared by the flask client and the requests sessions of authlib.
        The client authenticates on the token and introspection endpoints with client_secret_basic (authlib default).

        :return: Keyword arguments for the authlib client
        :rtype: dict
        """
        return {"client_id": self.auth_settings.SOGO_D_OPENID_CLIENT_NAME,
                "client_secret": self.auth_settings.SOGO_D_OPENID_CLIENT_SECRET,
                "scope": self.auth_settings.SOGO_D_OPENID_SCOPE,
                "default_timeout": OPENID_TIMEOUT}

    def _create_client(self) -> FlaskOAuth2App:
        """
        Create the authlib client for this domain.
        The settings are per domain and read from the database, so the client is built directly
        instead of being registered once in an authlib OAuth registry.
        #TODO cache the server metadata, authlib only caches it in this instance

        :return: The authlib flask client
        :rtype: FlaskOAuth2App
        """
        settings = self._get_client_settings()
        #The name is in the redis key of the state, it binds the state to this callback (kind and domain)
        name = self._framework.name
        return FlaskOAuth2App(self._framework,
                              name=name,
                              client_id=settings.pop("client_id"),
                              client_secret=settings.pop("client_secret"),
                              server_metadata_url=self.auth_settings.SOGO_D_OPENID_CONFIG_URL,
                              client_kwargs=settings)

    def _create_session(self, metadata: dict) -> OAuth2Session:
        """
        Create an authlib requests session for the token endpoint of the openid server, outside of the login flow.

        :param metadata: Metadata of the openid server
        :type metadata: dict
        :return: The authlib session, to use as a context manager
        :rtype: OAuth2Session
        """
        return OAuth2Session(token_endpoint=metadata.get("token_endpoint"), **self._get_client_settings())

    def get_login_location(self, ui_redirect: str) -> str:
        """
        Return the authorization url of the openid server.
        authlib generates the state and the nonce, they are kept in redis for the callback with ui_redirect.

        :param ui_redirect: UI url where the user is sent back after the callback, already checked
        :type ui_redirect: str
        :raises RequestException: If the openid server is unreachable or its configuration is invalid
        :return: The authorization url
        :rtype: str
        """
        try:
            rv = self._client.create_authorization_url(self.callback_url)
        except (requests.RequestException, ValueError, RuntimeError) as e:
            logger_auth.error("Cannot get openid configuration from %s: %s", self.auth_settings.SOGO_D_OPENID_CONFIG_URL, str(e))
            raise RequestException(error=err.ERROR_SSO_PROVIDER_UNREACHABLE) from e
        url = rv.pop("url") #Not needed for the callback
        #Same as authlib authorize_redirect, but the UI does the redirection
        rv[cs.SSO_STATE_UI_REDIRECT] = ui_redirect
        self._client.save_authorize_data(redirect_uri=self.callback_url, **rv)
        return url

    def authenticate_from_callback(self, callback_data: dict) -> IdentityProviderUserInfo:
        """
        Check the state, exchange the authorization code against the tokens, then get the user info.
        authlib reads the callback from the flask request, check the state against redis
        and validates the id_token (signature, issuer, audience, nonce) if there is one.
        ui_redirect is set as soon as the state is read, even if the authentication then fails.

        :param callback_data: Query parameters of the callback (code and state, or error and error_description)
        :type callback_data: dict
        :raises RequestException: If the state is invalid or the authentication failed
        :return: The user identity
        :rtype: IdentityProviderUserInfo
        """
        if "error" in callback_data or not callback_data.get("code"):
            #authlib fails before reading the state: read (and consume) it here to know where to send the user back
            state_data = self._framework.get_state_data(flask_session, callback_data.get("state"))
            if state_data is None:
                logger_auth.info("Openid callback with a missing, unknown, expired or already used state")
                raise RequestException(error=err.ERROR_SSO_INVALID_STATE)
            self.ui_redirect = state_data.get(cs.SSO_STATE_UI_REDIRECT, "")
            logger_auth.info("Openid server returned an error: %s - %s", callback_data.get("error"), callback_data.get("error_description"))
            raise RequestException("No authorization code given in openid callback", err.ERROR_SSO_LOGIN_FAILED)

        try:
            try:
                token = self._client.authorize_access_token()
            finally:
                #The state is read before the code exchange: the UI url is known even if the exchange fails
                self.ui_redirect = (self._framework.read_state_data or {}).get(cs.SSO_STATE_UI_REDIRECT, "")
            if self.auth_settings.SOGO_D_OPENID_FETCH_USER_PROFILE:
                user_info = dict(self._client.userinfo())
            else:
                user_info = dict(token.get("userinfo") or {}) #Claims of the validated id_token
        except MismatchingStateError as e:
            logger_auth.info("Openid callback with a missing, unknown, expired or already used state")
            raise RequestException(error=err.ERROR_SSO_INVALID_STATE) from e
        except OAuthError as e:
            logger_auth.info("Openid server returned an error: %s - %s", e.error, e.description)
            raise RequestException(error=err.ERROR_SSO_LOGIN_FAILED) from e
        except (AuthlibBaseError, JoseError) as e:
            logger_auth.info("Openid authentication refused: %s", str(e))
            raise RequestException(error=err.ERROR_SSO_LOGIN_FAILED) from e
        except (requests.RequestException, ValueError, RuntimeError) as e:
            logger_auth.error("Cannot get tokens or user info from openid server: %s", str(e))
            raise RequestException(error=err.ERROR_SSO_PROVIDER_UNREACHABLE) from e

        mail_field = self.auth_settings.SOGO_D_OPENID_EMAIL
        mail = user_info.get(mail_field)
        if not mail or not isinstance(mail, str):
            logger_auth.warning("Openid user info has no field %s (see SOGO_D_OPENID_EMAIL)", mail_field)
            raise RequestException(error=err.ERROR_SSO_LOGIN_FAILED)
        #token is an authlib OAuth2Token: expires_at is computed from expires_in
        return IdentityProviderUserInfo(mail=mail, claims=user_info,
                                        access_token=token.get("access_token", ""),
                                        refresh_token=token.get("refresh_token") or "",
                                        expires_at=int(token.get("expires_at") or 0))

    def check_access_token(self, access_token: str) -> bool:
        """
        Check that the access token is still valid on the openid server.
        The introspection endpoint (RFC 7662, authlib OAuth2Session.introspect_token) is used if the server has one,
        else the userinfo endpoint (authlib flask client): the token is valid if the server accepts it.
        Once valid, the token is not checked again for SOGO_D_OPENID_TOKEN_CHECK_INTERVAL seconds (0: always checked),
        the last valid check is kept in redis. If redis is unreachable, the token is checked every time.

        :param access_token: Access token of the user
        :type access_token: str
        :raises RequestException: If the openid server is unreachable or its configuration is invalid
        :return: True if the token is still valid
        :rtype: bool
        """
        if not access_token:
            return False
        interval = self.auth_settings.SOGO_D_OPENID_TOKEN_CHECK_INTERVAL
        #The token is hashed: it is the password of the user for the mail servers, it must not be readable in redis
        key = f"{cs.SSO_TOKEN_CHECK_KEY_PREFIX}{self.kind}:{sha256(access_token.encode('utf-8')).hexdigest()}"
        if interval and self._get_token_check(key):
            return True

        try:
            metadata = self._client.load_server_metadata()
            introspection_url = metadata.get("introspection_endpoint")
            if introspection_url:
                with self._create_session(metadata) as session:
                    resp = session.introspect_token(introspection_url, token=access_token, token_type_hint="access_token")
                resp.raise_for_status()
                is_valid = resp.json().get("active") is True
            else:
                is_valid = self._check_access_token_with_userinfo(access_token)
        except (requests.RequestException, ValueError, KeyError, RuntimeError) as e:
            logger_auth.error("Cannot check the access token on openid server: %s", str(e))
            raise RequestException(error=err.ERROR_SSO_PROVIDER_UNREACHABLE) from e

        if not is_valid:
            logger_auth.info("Openid access token is not valid anymore")
        elif interval:
            self._set_token_check(key, interval)
        return is_valid

    def _check_access_token_with_userinfo(self, access_token: str) -> bool:
        """
        Check the access token by calling the userinfo endpoint with it (authlib flask client)

        :param access_token: Access token of the user
        :type access_token: str
        :raises requests.RequestException: If the openid server is unreachable or answers with an error other than 401/403
        :return: False if the openid server refuses the token (401/403)
        :rtype: bool
        """
        try:
            self._client.userinfo(token={"access_token": access_token, "token_type": "Bearer"})
        except requests.HTTPError as e:
            if e.response is not None and e.response.status_code in (401, 403):
                return False
            raise
        return True

    def refresh_access_token(self, refresh_token: str) -> IdentityProviderTokens|None:
        """
        Get a new access token with the refresh token: authlib OAuth2Session.refresh_token (grant_type=refresh_token
        on the token endpoint, client_secret_basic, the scope is sent again). A refusal is raised by authlib as OAuthError.
        If the server rotates the refresh token, the new one is returned and the old one must not be used anymore.
        Else the refresh token given is returned as is.

        :param refresh_token: Refresh token of the user
        :type refresh_token: str
        :raises RequestException: If the openid server is unreachable or its answer is invalid
        :return: The new tokens, None if the server refused the refresh token (invalid_grant: session ended, user disabled...)
        :rtype: IdentityProviderTokens|None
        """
        if not refresh_token:
            return None
        try:
            metadata = self._client.load_server_metadata()
            with self._create_session(metadata) as session:
                token = session.refresh_token(metadata["token_endpoint"], refresh_token=refresh_token)
            access_token = token.get("access_token")
            if not access_token or not isinstance(access_token, str):
                raise ValueError("No access_token in the refresh response")
        except OAuthError as e:
            #RFC 6749 5.2: invalid_grant (refresh token expired or revoked), invalid_client...
            logger_auth.info("Openid server refused the refresh token: %s - %s", e.error, e.description)
            return None
        except (requests.RequestException, ValueError, KeyError, RuntimeError) as e:
            logger_auth.error("Cannot refresh the access token on openid server: %s", str(e))
            raise RequestException(error=err.ERROR_SSO_PROVIDER_UNREACHABLE) from e

        #token is an authlib OAuth2Token: refresh_token is the one given if the server did not rotate it,
        #expires_at is computed from expires_in
        return IdentityProviderTokens(access_token=access_token,
                                      refresh_token=token.get("refresh_token") or refresh_token,
                                      expires_at=int(token.get("expires_at") or 0))

    @staticmethod
    def _get_token_check(key: str) -> bool:
        """
        Return True if the access token has been checked valid less than SOGO_D_OPENID_TOKEN_CHECK_INTERVAL seconds ago

        :param key: Redis key of the token check
        :type key: str
        :return: True if the token check is still in redis
        :rtype: bool
        """
        cache = sogo_cache()
        try:
            return cache.get(key, str) is not None
        except (rexc.ConnectionError, rexc.TimeoutError) as e:
            logger_auth.warning("Cannot read the openid token check from redis: %s", repr(e))
            return False
        finally:
            cache.close()

    @staticmethod
    def _set_token_check(key: str, interval: int) -> None:
        """
        Keep in redis that the access token is valid, for SOGO_D_OPENID_TOKEN_CHECK_INTERVAL seconds

        :param key: Redis key of the token check
        :type key: str
        :param interval: SOGO_D_OPENID_TOKEN_CHECK_INTERVAL
        :type interval: int
        """
        cache = sogo_cache()
        try:
            cache.set(key, "1", interval)
        except (rexc.ConnectionError, rexc.TimeoutError) as e:
            logger_auth.warning("Cannot save the openid token check in redis: %s", repr(e))
        finally:
            cache.close()
